import { Alert, Button, Paper, Text } from '@mantine/core';
import { IconAlertTriangle, IconCheck, IconSparkles } from '@tabler/icons-react';
import { useMutation, useQuery } from '@tanstack/react-query';
import { useNavigate } from 'react-router-dom';
import { api } from '../api/client';
import { errorMessage } from '../lib/format';
import { useAiAvailable } from '../lib/useAiAvailable';
import classes from './AiCopilot.module.css';

/**
 * "Before you report" on the report form: a known issue on the chosen service shows at once (from the service
 * map, no AI needed); with AI on, the employee can ask for a few safe steps to try first.
 */
export function SelfHelp({ title, description, serviceId }: { title: string; description: string; serviceId: string | null }) {
  const navigate = useNavigate();
  const aiAvailable = useAiAvailable();
  const health = useQuery({ queryKey: ['catalog', 'health'], queryFn: api.catalog.health, staleTime: 30_000 });
  const service = health.data?.find((s) => String(s.id) === serviceId);
  const known = service && service.health !== 'OPERATIONAL' ? service : null;

  const help = useMutation({
    mutationFn: () =>
      api.ai.selfHelp({ title: title.trim(), description: description.trim(), serviceId: serviceId ? Number(serviceId) : null }),
  });
  const canAsk = aiAvailable && title.trim().length >= 4;
  const h = help.data;

  if (!known && !aiAvailable) return null;

  return (
    <Paper withBorder p="lg">
      <div className={classes.head}>
        <IconSparkles size={18} stroke={1.6} />
        <Text fw={700}>Before you report</Text>
      </div>

      {known && (
        <Alert mt="sm" color="stamp" variant="outline" icon={<IconAlertTriangle size={16} />} title={`Known issue: ${known.name}`}>
          IT already knows {known.name} is {known.health === 'OUTAGE' ? 'down' : known.health === 'IMPACTED' ? 'affected by a related problem' : 'having problems'}
          {known.openIncidents > 0 ? ` (${known.openIncidents} reports so far)` : ''} and is working on it. You only need to report if
          your problem is different.
        </Alert>
      )}

      {aiAvailable && !h && (
        <>
          <Text size="sm" c="dimmed" mt="sm" mb="sm">
            Get a few safe things to try first, based on how similar problems were fixed here.
          </Text>
          <Button variant="outline" leftSection={<IconSparkles size={16} />} disabled={!canAsk} loading={help.isPending} onClick={() => help.mutate()}>
            Try a quick fix
          </Button>
          {!canAsk && (
            <Text size="xs" c="dimmed" mt={6}>
              Write a short title first.
            </Text>
          )}
          {help.error && (
            <Text size="sm" c="var(--app-stamp)" mt="sm">
              {errorMessage(help.error)}
            </Text>
          )}
        </>
      )}

      {h && (
        <>
          {h.steps.length > 0 && (
            <ol className={classes.steps}>
              {h.steps.map((s) => (
                <li key={s}>{s}</li>
              ))}
            </ol>
          )}
          {h.note && (
            <Text size="sm" mt="sm">
              {h.note}
            </Text>
          )}
          {h.canSelfFix && (
            <Button mt="sm" variant="filled" leftSection={<IconCheck size={16} />} onClick={() => navigate('/')}>
              That fixed it
            </Button>
          )}
          <Text size="xs" c="dimmed" mt="sm">
            {h.model ? `Generated by Google Gemini (${h.model}). ` : ''}Still broken? Carry on with the report.
          </Text>
        </>
      )}
    </Paper>
  );
}
