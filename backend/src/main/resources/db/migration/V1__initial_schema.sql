-- ---------------------------------------------------------------------------------------------------------------------
-- Users: JOINED inheritance. One row in users for every person, plus one row in exactly one subtype table.
-- ---------------------------------------------------------------------------------------------------------------------

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(120) NOT NULL,
    email         VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_email_lowercase CHECK (email = LOWER(email))
);

CREATE TABLE employees (
    id         BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    department VARCHAR(80),
    location   VARCHAR(80)
);

CREATE TABLE technicians (
    id                   BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    support_level        VARCHAR(20) NOT NULL,
    experience_years     INTEGER     NOT NULL,
    max_active_incidents INTEGER     NOT NULL,
    availability         VARCHAR(20) NOT NULL,
    CONSTRAINT ck_technicians_support_level
        CHECK (support_level IN ('L1_TECHNICIAN', 'L2_TEAM_LEAD', 'L3_SYSTEM_ADMIN', 'L4_IT_MANAGER')),
    CONSTRAINT ck_technicians_availability
        CHECK (availability IN ('AVAILABLE', 'BUSY', 'OFF_DUTY', 'ON_LEAVE')),
    CONSTRAINT ck_technicians_experience CHECK (experience_years BETWEEN 0 AND 50),
    CONSTRAINT ck_technicians_capacity CHECK (max_active_incidents BETWEEN 1 AND 50)
);

CREATE TABLE administrators (
    id BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE
);


-- ---------------------------------------------------------------------------------------------------------------------
-- Catalogue: categories and IT services
-- ---------------------------------------------------------------------------------------------------------------------

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(60)  NOT NULL,
    description VARCHAR(500),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_categories_name UNIQUE (name)
);

CREATE TABLE category_keywords (
    category_id BIGINT      NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
    keyword     VARCHAR(40) NOT NULL,
    PRIMARY KEY (category_id, keyword),
    CONSTRAINT ck_category_keywords_lowercase CHECK (keyword = LOWER(keyword))
);

-- A technician's proficiency (1-5) in a category. Value objects: no id of their own.
CREATE TABLE technician_skills (
    technician_id BIGINT  NOT NULL REFERENCES technicians (id) ON DELETE CASCADE,
    category_id   BIGINT  NOT NULL REFERENCES categories (id),
    proficiency   INTEGER NOT NULL,
    CONSTRAINT uq_technician_skills UNIQUE (technician_id, category_id),
    CONSTRAINT ck_technician_skills_proficiency CHECK (proficiency BETWEEN 1 AND 5)
);

CREATE TABLE it_services (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(80)  NOT NULL,
    description VARCHAR(500),
    criticality VARCHAR(20)  NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    CONSTRAINT uq_it_services_name UNIQUE (name),
    CONSTRAINT ck_it_services_criticality CHECK (criticality IN ('LOW', 'MEDIUM', 'HIGH', 'MISSION_CRITICAL')),
    CONSTRAINT ck_it_services_status
        CHECK (status IN ('OPERATIONAL', 'DEGRADED', 'PARTIAL_OUTAGE', 'MAJOR_OUTAGE', 'MAINTENANCE'))
);

-- Service dependency graph: service_id depends on depends_on_id. Cycles longer than 1 are prevented in Java.
CREATE TABLE service_dependencies (
    service_id    BIGINT NOT NULL REFERENCES it_services (id) ON DELETE CASCADE,
    depends_on_id BIGINT NOT NULL REFERENCES it_services (id) ON DELETE CASCADE,
    PRIMARY KEY (service_id, depends_on_id),
    CONSTRAINT ck_service_dependencies_not_self CHECK (service_id <> depends_on_id)
);


-- ---------------------------------------------------------------------------------------------------------------------
-- SLA policies
-- ---------------------------------------------------------------------------------------------------------------------

CREATE TABLE sla_policies (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    priority           VARCHAR(2)       NOT NULL,
    service_id         BIGINT REFERENCES it_services (id) ON DELETE CASCADE,  -- NULL = applies to all services
    response_minutes   BIGINT           NOT NULL,
    resolution_minutes BIGINT           NOT NULL,
    warning_threshold  DOUBLE PRECISION NOT NULL,
    CONSTRAINT ck_sla_policies_priority CHECK (priority IN ('P1', 'P2', 'P3', 'P4')),
    CONSTRAINT ck_sla_policies_targets CHECK (response_minutes >= 1 AND resolution_minutes >= response_minutes),
    CONSTRAINT ck_sla_policies_threshold CHECK (warning_threshold BETWEEN 0.5 AND 0.95)
);

-- At most one generic policy per priority, and at most one per (priority, service).
-- Two partial indexes, because a plain UNIQUE constraint treats NULL service_ids as all different.
CREATE UNIQUE INDEX uq_sla_policies_generic ON sla_policies (priority) WHERE service_id IS NULL;
CREATE UNIQUE INDEX uq_sla_policies_service ON sla_policies (priority, service_id) WHERE service_id IS NOT NULL;


-- ---------------------------------------------------------------------------------------------------------------------
-- Incidents. Embedded value objects (priority, SLA tracker, resolution, feedback) are column groups with a prefix.
-- ---------------------------------------------------------------------------------------------------------------------

CREATE TABLE incidents (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number                 VARCHAR(20)   NOT NULL,
    title                  VARCHAR(150)  NOT NULL,
    description            VARCHAR(4000) NOT NULL,
    reporter_id            BIGINT        NOT NULL REFERENCES employees (id),
    service_id             BIGINT        NOT NULL REFERENCES it_services (id),
    category_id            BIGINT REFERENCES categories (id),
    impact                 VARCHAR(20)   NOT NULL,
    urgency                VARCHAR(20)   NOT NULL,
    affected_users         INTEGER       NOT NULL,
    status                 VARCHAR(20)   NOT NULL,
    assignee_id            BIGINT REFERENCES technicians (id),

    -- Priority (value object)
    priority_level         VARCHAR(2),
    priority_score         DOUBLE PRECISION,
    priority_rationale     VARCHAR(300),

    -- SLA tracker (value object): targets are a snapshot of the policy at the time the SLA started
    sla_policy_id          BIGINT REFERENCES sla_policies (id) ON DELETE SET NULL,
    sla_response_minutes   BIGINT,
    sla_resolution_minutes BIGINT,
    sla_warning_threshold  DOUBLE PRECISION,
    sla_started_at         TIMESTAMPTZ,
    sla_responded_at       TIMESTAMPTZ,
    sla_resolved_at        TIMESTAMPTZ,
    sla_paused_since       TIMESTAMPTZ,
    sla_paused_seconds     BIGINT        NOT NULL DEFAULT 0,

    -- Resolution (value object)
    resolution_summary     VARCHAR(2000),
    resolution_root_cause  VARCHAR(2000),
    resolution_code        VARCHAR(30),
    resolved_by_id         BIGINT REFERENCES technicians (id),
    resolved_at            TIMESTAMPTZ,

    -- Feedback (value object)
    feedback_accepted      BOOLEAN,
    feedback_rating        INTEGER,
    feedback_comment       VARCHAR(1000),
    feedback_given_at      TIMESTAMPTZ,

    duplicate_of_id        BIGINT REFERENCES incidents (id),
    cancellation_reason    VARCHAR(500),
    created_at             TIMESTAMPTZ   NOT NULL,
    updated_at             TIMESTAMPTZ   NOT NULL,
    closed_at              TIMESTAMPTZ,
    version                BIGINT        NOT NULL DEFAULT 0,

    CONSTRAINT uq_incidents_number UNIQUE (number),
    CONSTRAINT ck_incidents_number_format CHECK (number ~ '^INC-[0-9]{4}-[0-9]{6}$'),
    CONSTRAINT ck_incidents_status CHECK (status IN ('NEW', 'CLASSIFIED', 'ASSIGNED', 'ACKNOWLEDGED', 'IN_PROGRESS',
                                                     'ON_HOLD', 'RESOLVED', 'VERIFIED', 'CLOSED', 'CANCELLED')),
    CONSTRAINT ck_incidents_impact CHECK (impact IN ('LOW', 'MEDIUM', 'HIGH', 'EXTENSIVE')),
    CONSTRAINT ck_incidents_urgency CHECK (urgency IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_incidents_priority CHECK (priority_level IS NULL OR priority_level IN ('P1', 'P2', 'P3', 'P4')),
    CONSTRAINT ck_incidents_affected_users CHECK (affected_users BETWEEN 1 AND 1000000),
    CONSTRAINT ck_incidents_rating CHECK (feedback_rating IS NULL OR feedback_rating BETWEEN 1 AND 5),
    CONSTRAINT ck_incidents_not_own_duplicate CHECK (duplicate_of_id IS NULL OR duplicate_of_id <> id),
    -- Lifecycle invariants that must hold whatever the application does:
    CONSTRAINT ck_incidents_classified_has_priority
        CHECK (status IN ('NEW', 'CANCELLED') OR (category_id IS NOT NULL AND priority_level IS NOT NULL)),
    CONSTRAINT ck_incidents_closed_has_time CHECK (status NOT IN ('CLOSED', 'CANCELLED') OR closed_at IS NOT NULL)
);

-- Indexes for the most common searches and for SLA monitoring / workload queries.
CREATE INDEX ix_incidents_status ON incidents (status);
CREATE INDEX ix_incidents_assignee_status ON incidents (assignee_id, status);
CREATE INDEX ix_incidents_reporter ON incidents (reporter_id);
CREATE INDEX ix_incidents_service ON incidents (service_id);
CREATE INDEX ix_incidents_category ON incidents (category_id);
CREATE INDEX ix_incidents_priority ON incidents (priority_level);
CREATE INDEX ix_incidents_created_at ON incidents (created_at);

CREATE TABLE incident_notes (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id   BIGINT        NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    author_id     BIGINT        NOT NULL REFERENCES users (id),
    text          VARCHAR(4000) NOT NULL,
    internal_only BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ   NOT NULL
);
CREATE INDEX ix_incident_notes_incident ON incident_notes (incident_id);

CREATE TABLE incident_info_requests (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT        NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    asked_by_id BIGINT        NOT NULL REFERENCES technicians (id),
    question    VARCHAR(1000) NOT NULL,
    asked_at    TIMESTAMPTZ   NOT NULL,
    answer      VARCHAR(2000),
    answered_at TIMESTAMPTZ
);
CREATE INDEX ix_incident_info_requests_incident ON incident_info_requests (incident_id);
