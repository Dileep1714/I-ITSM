-- =====================================================================================================================
-- Audit trail, in-app notifications, SLA violation records, escalation tracking
-- =====================================================================================================================

-- SLA signal flags (each warning/breach is raised exactly once) and escalation tracking.
ALTER TABLE incidents
    ADD COLUMN sla_response_warned            BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN sla_resolution_warned          BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN sla_response_breach_recorded   BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN sla_resolution_breach_recorded BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN escalation_level               VARCHAR(20),
    ADD COLUMN last_escalated_at              TIMESTAMPTZ,
    ADD CONSTRAINT ck_incidents_escalation_level CHECK (escalation_level IS NULL OR escalation_level IN
        ('L1_TECHNICIAN', 'L2_TEAM_LEAD', 'L3_SYSTEM_ADMIN', 'L4_IT_MANAGER'));

CREATE INDEX ix_incidents_open_sla ON incidents (status) WHERE sla_started_at IS NOT NULL;


-- ---------------------------------------------------------------------------------------------------------------------
-- Audit trail: one row per thing that happened to an incident. APPEND-ONLY.
-- actor_name is copied (not only referenced) so history stays readable even if a user is later renamed or removed.
-- ---------------------------------------------------------------------------------------------------------------------

CREATE TABLE audit_entries (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id         BIGINT        NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    incident_number     VARCHAR(20)   NOT NULL,
    action              VARCHAR(40)   NOT NULL,
    previous_status     VARCHAR(20),
    new_status          VARCHAR(20),
    description         VARCHAR(1000) NOT NULL,
    actor_id            BIGINT REFERENCES users (id) ON DELETE SET NULL,  -- NULL = the system (SLA monitor)
    actor_name          VARCHAR(120)  NOT NULL,
    visible_to_reporter BOOLEAN       NOT NULL,
    occurred_at         TIMESTAMPTZ   NOT NULL
);
CREATE INDEX ix_audit_entries_incident ON audit_entries (incident_id, occurred_at);
CREATE INDEX ix_audit_entries_occurred_at ON audit_entries (occurred_at);

-- Enforce append-only in the database itself: history cannot be rewritten, even with direct SQL access.
-- (Deleting an incident still removes its entries via ON DELETE CASCADE.)
CREATE FUNCTION forbid_audit_update() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'audit_entries is append-only: rows cannot be updated';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER audit_entries_append_only
    BEFORE UPDATE ON audit_entries
    FOR EACH ROW EXECUTE FUNCTION forbid_audit_update();


-- ---------------------------------------------------------------------------------------------------------------------
-- SLA violations: a permanent record of every missed deadline, for reporting.
-- ---------------------------------------------------------------------------------------------------------------------

CREATE TABLE sla_violations (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id    BIGINT      NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    kind           VARCHAR(20) NOT NULL,
    priority_level VARCHAR(2)  NOT NULL,
    deadline       TIMESTAMPTZ NOT NULL,
    detected_at    TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_sla_violations UNIQUE (incident_id, kind),
    CONSTRAINT ck_sla_violations_kind CHECK (kind IN ('RESPONSE', 'RESOLUTION'))
);
CREATE INDEX ix_sla_violations_detected_at ON sla_violations (detected_at);


-- ---------------------------------------------------------------------------------------------------------------------
-- In-app notifications (the inbox / bell icon). Email and SMS are sent, not stored here.
-- ---------------------------------------------------------------------------------------------------------------------

CREATE TABLE notifications (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id    BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    incident_id     BIGINT REFERENCES incidents (id) ON DELETE CASCADE,
    incident_number VARCHAR(20),
    type            VARCHAR(40)   NOT NULL,
    title           VARCHAR(200)  NOT NULL,
    message         VARCHAR(1000) NOT NULL,
    created_at      TIMESTAMPTZ   NOT NULL,
    read_at         TIMESTAMPTZ
);
CREATE INDEX ix_notifications_recipient ON notifications (recipient_id, created_at DESC);
CREATE INDEX ix_notifications_unread ON notifications (recipient_id) WHERE read_at IS NULL;
