-- =====================================================================================================================
-- Incident attachments: photos / screenshots of a problem, added from the web app or taken with the phone camera.
-- The image bytes live in the database (simple to back up and deploy; size is capped by the application at 5 MB per
-- file and 10 files per incident). Listing attachments never reads the content column.
-- =====================================================================================================================

CREATE TABLE incident_attachments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id   BIGINT       NOT NULL REFERENCES incidents (id) ON DELETE CASCADE,
    uploaded_by   BIGINT       NOT NULL REFERENCES users (id),
    file_name     VARCHAR(200) NOT NULL,
    content_type  VARCHAR(50)  NOT NULL,
    size_bytes    BIGINT       NOT NULL CHECK (size_bytes > 0),
    content       BYTEA        NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL
);
CREATE INDEX ix_incident_attachments_incident ON incident_attachments (incident_id);
