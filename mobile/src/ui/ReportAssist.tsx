import Ionicons from '@expo/vector-icons/Ionicons';
import { useMutation, useQuery } from '@tanstack/react-query';
import { useRef, useState } from 'react';
import { ActivityIndicator, Pressable, ScrollView, type ScrollViewInstance, StyleSheet, Text, TextInput, View } from 'react-native';
import { api } from '../api/client';
import type { ChatTurn, ReportDraft } from '../api/types';
import { errorMessage, humanize } from '../lib/format';
import { Button, T } from './kit';
import { FIGURE, useColors } from './theme';

/** Whether the server has an AI key configured: AI features are hidden when it does not. */
export function useAiAvailable() {
  const status = useQuery({ queryKey: ['ai', 'status'], queryFn: api.ai.status, staleTime: 5 * 60_000 });
  return status.data?.available === true;
}

/**
 * "Before you report": a known issue on the chosen service shows at once (no AI needed); with AI on, the employee
 * can ask for a few safe steps to try first. Past incidents only inform the model and are never shown.
 */
export function BeforeYouReport({ title, description, serviceId, onFixed }: { title: string; description: string; serviceId: number | null; onFixed: () => void }) {
  const c = useColors();
  const ai = useAiAvailable();
  const health = useQuery({ queryKey: ['catalog', 'health'], queryFn: api.catalog.health, staleTime: 30_000 });
  const known = health.data?.find((s) => s.id === serviceId && s.health !== 'OPERATIONAL');
  const help = useMutation({ mutationFn: () => api.ai.selfHelp({ title: title.trim(), description: description.trim(), serviceId }) });
  const h = help.data;
  if (!known && !ai) return null;

  return (
    <View style={[styles.card, { backgroundColor: c.surface, borderColor: c.border }]}>
      <Text style={[styles.label, { color: c.primary }]}>BEFORE YOU REPORT</Text>
      {known && (
        <View style={[styles.known, { borderColor: c.danger }]}>
          <Ionicons name="warning-outline" size={18} color={c.danger} />
          <T v="small" style={{ flex: 1 }}>
            <T v="small" style={{ fontWeight: '700' }}>
              Known issue: {known.name}.{' '}
            </T>
            IT already knows and is working on it{known.openIncidents > 0 ? ` (${known.openIncidents} reports so far)` : ''}. Only report if your problem is different.
          </T>
        </View>
      )}
      {ai && !h && (
        <>
          <T v="small" muted>
            Get a few safe things to try first, based on how similar problems were fixed here.
          </T>
          <Button label="Try a quick fix" icon="sparkles-outline" variant="outlined" disabled={title.trim().length < 4} loading={help.isPending} onPress={() => help.mutate()} />
          {title.trim().length < 4 && (
            <T v="small" muted>
              Write what's wrong first.
            </T>
          )}
          {help.error ? <T v="small" color={c.danger}>{errorMessage(help.error)}</T> : null}
        </>
      )}
      {h && (
        <>
          {h.steps.map((s, i) => (
            <View key={s} style={{ flexDirection: 'row', gap: 8 }}>
              <Text style={{ fontFamily: FIGURE, color: c.primary }}>{i + 1}.</Text>
              <T v="small" style={{ flex: 1 }}>
                {s}
              </T>
            </View>
          ))}
          {h.note ? <T v="small">{h.note}</T> : null}
          {h.canSelfFix && <Button label="That fixed it" icon="checkmark" onPress={onFixed} />}
          <T v="small" muted>
            {h.model ? `Generated by Google Gemini (${h.model}). ` : ''}Still broken? Carry on with the report.
          </T>
        </>
      )}
    </View>
  );
}

const OPENING = "Hi! Tell me what's going wrong, in your own words. I'll ask a couple of questions and fill in the report for you.";

/** Chat-based reporting: the assistant prepares a draft that fills the form; the employee submits it. */
export function ReportChat({ onUseDraft }: { onUseDraft: (draft: ReportDraft) => void }) {
  const c = useColors();
  const [turns, setTurns] = useState<ChatTurn[]>([]);
  const [text, setText] = useState('');
  const [draft, setDraft] = useState<ReportDraft | null>(null);
  const [model, setModel] = useState<string | null>(null);
  const scroll = useRef<ScrollViewInstance>(null);

  const chat = useMutation({
    mutationFn: (messages: ChatTurn[]) => api.ai.reportChat(messages),
    onSuccess: (reply, messages) => {
      setTurns([...messages, { role: 'assistant', text: reply.reply }]);
      setModel(reply.model);
      if (reply.ready && reply.draft) setDraft(reply.draft);
      setTimeout(() => scroll.current?.scrollToEnd({ animated: true }), 50);
    },
  });

  const send = () => {
    const message = text.trim();
    if (!message || chat.isPending) return;
    const next: ChatTurn[] = [...turns, { role: 'user', text: message }];
    setTurns(next);
    setText('');
    chat.mutate(next);
    setTimeout(() => scroll.current?.scrollToEnd({ animated: true }), 50);
  };

  const bubble = (role: 'user' | 'assistant', body: React.ReactNode, key: string | number) => (
    <View
      key={key}
      style={[
        styles.bubble,
        role === 'user'
          ? { alignSelf: 'flex-end', backgroundColor: c.primary, borderColor: c.primary }
          : { alignSelf: 'flex-start', backgroundColor: c.surface, borderColor: c.border },
      ]}
    >
      {typeof body === 'string' ? <Text style={{ color: role === 'user' ? c.onPrimary : c.text, fontSize: 15, lineHeight: 21 }}>{body}</Text> : body}
    </View>
  );

  return (
    <View style={{ gap: 12 }}>
      <ScrollView ref={scroll} style={{ maxHeight: 420 }} contentContainerStyle={{ gap: 10 }} nestedScrollEnabled>
        {bubble('assistant', OPENING, 'opening')}
        {turns.map((t, i) => bubble(t.role, t.text, i))}
        {chat.isPending && bubble('assistant', <ActivityIndicator size="small" color={c.primary} />, 'typing')}
      </ScrollView>
      {chat.error ? <T v="small" color={c.danger}>{errorMessage(chat.error)}</T> : null}

      {draft && (
        <View style={[styles.draft, { borderColor: c.primary, backgroundColor: c.surface }]}>
          <Text style={[styles.label, { color: c.primary }]}>PREPARED REPORT</Text>
          <T style={{ fontWeight: '700' }}>{draft.title}</T>
          <T v="small" muted>
            {[draft.serviceName, draft.categoryName, `${humanize(draft.impact)} impact`, `${humanize(draft.urgency)} urgency`].filter(Boolean).join(' · ')}
          </T>
          {!draft.serviceId && (
            <T v="small" color={c.danger}>
              No matching IT service: choose the closest one in the form.
            </T>
          )}
          <Button label="Review this report" icon="arrow-forward" onPress={() => onUseDraft(draft)} />
        </View>
      )}

      <View style={styles.composer}>
        <TextInput
          value={text}
          onChangeText={setText}
          placeholder={draft ? 'Add anything else…' : 'Describe the problem…'}
          placeholderTextColor={c.muted}
          multiline
          style={[styles.input, { backgroundColor: c.surfaceAlt, color: c.text }]}
          accessibilityLabel="Message to the assistant"
        />
        <Pressable
          onPress={send}
          disabled={!text.trim() || chat.isPending}
          style={[styles.send, { backgroundColor: c.primary, opacity: !text.trim() || chat.isPending ? 0.4 : 1 }]}
          accessibilityRole="button"
          accessibilityLabel="Send"
        >
          <Ionicons name="send" size={18} color={c.onPrimary} />
        </Pressable>
      </View>
      {model && (
        <T v="small" muted>
          Generated by Google Gemini ({model}). Check it before acting on it.
        </T>
      )}
    </View>
  );
}

const styles = StyleSheet.create({
  card: { borderRadius: 14, borderWidth: StyleSheet.hairlineWidth, padding: 16, gap: 10 },
  label: { fontSize: 10.5, fontWeight: '800', letterSpacing: 1.1 },
  known: { flexDirection: 'row', gap: 8, borderWidth: 1.5, borderRadius: 4, padding: 10 },
  bubble: { maxWidth: '86%', borderWidth: StyleSheet.hairlineWidth, borderRadius: 14, paddingHorizontal: 14, paddingVertical: 10 },
  draft: { borderWidth: 2, borderRadius: 12, padding: 14, gap: 6 },
  composer: { flexDirection: 'row', gap: 8, alignItems: 'flex-end' },
  input: { flex: 1, minHeight: 46, maxHeight: 120, borderRadius: 12, paddingHorizontal: 14, paddingTop: 12, paddingBottom: 12, fontSize: 16 },
  send: { width: 46, height: 46, borderRadius: 23, alignItems: 'center', justifyContent: 'center' },
});
